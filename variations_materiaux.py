def stable_hash(*values: int) -> int:
    result = 2166136261
    for value in values:
        result = ((result ^ (int(value) & 0xffffffff)) * 16777619) & 0xffffffff
    return result

def material_variant(family: str, world_x: int, world_y: int, seed: int = 0) -> MaterialVariant:
    """Return the same weathered finish for a world tile on every frame."""
    starts = {"concrete": 0, "brick": 128, "stone": 256, "wood": 384, "soil": 512, "grass": 640, "metal": 768, "cloth": 896}
    start = starts.get(family, 0)
    return VARIANTS[start + stable_hash(world_x, world_y, seed) % 128]

def lit_color(variant: MaterialVariant, factor: float) -> tuple[int, int, int]:
    return tuple(max(0, min(255, int(channel * factor))) for channel in variant[2])

def wear_profile(variant: MaterialVariant) -> tuple[float, float, float, int]:
    return variant[5], variant[6], variant[7], variant[8]
